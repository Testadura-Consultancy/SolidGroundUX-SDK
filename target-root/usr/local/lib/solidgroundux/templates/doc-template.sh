# Documentation syntax quick reference:
#
#   Section indicators:
# >   # - Heading              Level 1 / top-level section
# >   # -- Section             Level 2 section
# >   # --- Subsection         Level 3 subsection
#
#   Documentation item/header indicators:
# >    # fn:                    Function or method
# >    # var:                   Variable
# >    # cls:                   Class
# >    # doc:                   General documentation
# >    # fn$ / var$ / cls$ / doc$
#                              Template documentation variants
#
#   Documentation and style hints:
# >    # > text                 Plain documentation / normal style
# >    # : text                 label
# >    # . text                 highlight
# >    # ! text                 emphasis
# >    # _ text                 underline
# >    # ~ text                 quote / aside
# >    # - text                 list item
#                              indent is reserved; leading whitespace prevents marker parsing
#
#   Aligning documentation columns:
# >    # > fn: <> Function documentation
# >    # > var: <> Variable documentation
# >    # > doc: <> General documentation
# >    @<> aligns columns across consecutive documentation lines
#
#   Showing images in documentation:
# >   # . Images               Begin an image group (Image is also accepted; : may replace .)
# >   # filename.png :: Caption
# >   #                        Blank documentation line ends the image block
#
#   Showing tables in documentation:
# >   # . Table                Begin a table
# >   # ! Header 1 :: Header 2 First row is the semantic header; ! is optional
# >   # Value 1 :: Value 2     Following rows use normal documentation lines
# >   #                        Blank documentation line ends the table
